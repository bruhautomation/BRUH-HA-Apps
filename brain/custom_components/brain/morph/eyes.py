"""brAIn's eyes on Home Assistant's own dashboards.

brAIn photographs a screen before it answers about how it looks
(`screenshot_panel`), and until 5.1 it could photograph its own panel, the
other BRUH panels and Morph drawn in a stand-in page, but never a real Home
Assistant dashboard: the browser in brAIn's container could not sign in to
Home Assistant's frontend. This is that sign-in.

``morph/eyes`` (administrators only; the add-on asks it over the Supervisor's
socket, whose user is one) answers a short-lived access token for a
system user of brAIn's own, **brAIn (screenshots)**, with HA's address
seen from inside (its port and whether it is https) and every dashboard
with its tabs. The add-on's Chromium puts that token in the frontend's own
token store (`localStorage.hassTokens`), the way Home Assistant's own
screenshot tooling does, and opens the dashboard as that user.

* The user is **system-generated**: nobody can log in as it, it has no
  password, and it is listed apart from people in Settings › People.
* It is an **administrator**, because a dashboard can be shown to
  administrators only and brAIn must be able to see every one.
* Its access token lives as long as Home Assistant's default (30 minutes)
  and is handed only to a caller that is itself an administrator. The
  add-on uses it for one capture and keeps it nowhere.
* What the page can DO with it is held by the add-on's browser guard: no
  service call, no save, no write of any kind leaves the page
  (`devloop/screens.py`, `_HA_SOCKET_GUARD_JS`).
"""
from __future__ import annotations

import logging

import voluptuous as vol

from homeassistant.components import websocket_api
from homeassistant.core import HomeAssistant

from . import lovelace

_LOGGER = logging.getLogger(__name__)

EYES_NAME = "brAIn (screenshots)"
GROUP_ADMIN = "system-admin"  # homeassistant.auth.const.GROUP_ID_ADMIN


async def eyes_user(hass: HomeAssistant):
    """brAIn's system user, made the first time it is asked for."""
    for user in await hass.auth.async_get_users():
        if user.system_generated and user.name == EYES_NAME:
            if not user.is_active:
                await hass.auth.async_activate_user(user)
            return user
    _LOGGER.info("brAIn: adding the system user %s, for photographing dashboards", EYES_NAME)
    return await hass.auth.async_create_system_user(EYES_NAME, group_ids=[GROUP_ADMIN])


async def mint(hass: HomeAssistant) -> dict:
    """A fresh access token for brAIn's eyes, and how long it lives."""
    user = await eyes_user(hass)
    refresh = next(iter(user.refresh_tokens.values()), None)
    if refresh is None:
        refresh = await hass.auth.async_create_refresh_token(user)
    token = hass.auth.async_create_access_token(refresh)
    return {"access_token": token,
            "expires_in": int(refresh.access_token_expiration.total_seconds())}


def view_rows(cfg) -> list[dict]:
    """A dashboard's tabs as (index, path, title, type); an untouched
    default dashboard (generated by the frontend, nothing stored) is one."""
    views = cfg.get("views") if isinstance(cfg, dict) else None
    if not isinstance(views, list) or not views:
        return [{"index": 0, "path": "0", "title": "Overview", "type": "auto"}]
    out = []
    for i, v in enumerate(views):
        if not isinstance(v, dict):
            continue
        out.append({"index": i, "path": str(v.get("path") or i), "title": str(v.get("title") or v.get("path") or f"Tab {i + 1}"),
                    "type": str(v.get("type") or ("sections" if v.get("sections") else "masonry"))})
    return out


async def catalog(hass: HomeAssistant) -> list[dict]:
    """Every dashboard Home Assistant has, with its tabs."""
    out = []
    for row in await hass.async_add_executor_job(lovelace.describe, hass):
        cfg = await lovelace.load_config(hass, row["key"])
        out.append({**row, "views": view_rows(cfg)})
    return out


def address(hass: HomeAssistant) -> dict:
    api = getattr(hass.config, "api", None)
    return {"port": int(getattr(api, "port", None) or 8123), "ssl": bool(getattr(api, "use_ssl", False))}


@websocket_api.websocket_command({vol.Required("type"): "morph/eyes",
                                  vol.Optional("token", default=True): bool})
@websocket_api.require_admin
@websocket_api.async_response
async def ws_eyes(hass: HomeAssistant, connection, msg) -> None:
    out = {**address(hass), "dashboards": await catalog(hass)}
    if msg.get("token", True):
        out.update(await mint(hass))
    connection.send_result(msg["id"], out)
